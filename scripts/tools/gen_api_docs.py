"""Regenerate docs/api.md from sciplot's signatures and docstrings.

    python scripts/tools/gen_api_docs.py
"""
import inspect
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
warnings.simplefilter("ignore")
import sciplot as sp  # noqa: E402

MODULES = [
    ("styles", "Themes × venues: `sp.use`, `sp.context`, `sp.theme_colors`."),
    ("layout", "Exact-size figures, panel letters and axes polish. `VENUES` holds every venue spec."),
    ("palettes", "The palette bank, colormaps, palette search and helpers. "
                 "Also exposes `BANK`, `SEMANTIC`, `CMAPS`, `NEUTRALS`, `BACKGROUNDS`."),
    ("color", "Colour math in OKLab/OKLCH and CIELAB: mixing, contrast, ΔE2000, CVD simulation."),
    ("annotate", "Direct labels, significance brackets, scale bars, event markers, colorbars."),
    ("neuro", "Panel recipes for comp-neuro / NeuroAI and presets for brain-viz packages."),
    ("schematic", "Model diagrams on a millimetre canvas (`canvas(ax)` first)."),
    ("check", "Figure linter and palette CVD audit."),
    ("export", "Saving with editable fonts, previews."),
]
TOP = ["use", "context", "theme_colors", "figure", "figsize", "label_panels", "align_labels",
       "offset_spines", "range_frame", "trim_spines", "max_ticks", "save", "preview", "colors",
       "cmap", "highlight", "paired", "search", "semantic", "shades", "label_lines", "label_point",
       "sig_bracket", "scale_bar", "event_lines", "shade", "slim_colorbar"]


def doc_of(f):
    d = inspect.getdoc(f) or ""
    return " ".join(d.split("\n\n")[0].split()).replace("|", "\\|")


def main():
    out = ["# API reference", "",
           "<!-- generated by scripts/tools/gen_api_docs.py; do not edit by hand -->", "",
           f"`sciplot` {sp.__version__}. `import sciplot as sp`. Each module is also available as `sp.<module>`.", "",
           "## Top-level shortcuts", "",
           "| `sp.` name | Defined in |", "|---|---|"]
    for n in TOP:
        f = getattr(sp, n)
        out.append(f"| `{n}` | `{f.__module__.split('.')[-1]}.{f.__name__}` |")
    for mod, blurb in MODULES:
        m = getattr(sp, mod)
        out += ["", f"## `sciplot.{mod}`", "", blurb, "", "| Function | Description |", "|---|---|"]
        for n, f in inspect.getmembers(m, inspect.isfunction):
            if n.startswith("_") or f.__module__ != m.__name__:
                continue
            sig = str(inspect.signature(f)).replace("|", "\\|")
            out.append(f"| `{n}{sig}` | {doc_of(f)} |")
    path = ROOT / "docs" / "api.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
